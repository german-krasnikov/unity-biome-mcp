"""TDD tests for diagnostics: debug_animator, debug_physics."""
import pytest
from unittest.mock import AsyncMock


_ARGS = lambda **kw: {k: v for k, v in kw.items() if v is not None}


@pytest.mark.asyncio
async def test_debug_animator_sends_path(monkeypatch):
    import unity_mcp.tools.generated.catalog_tools as mod  # both tools are generated by the tool catalog
    monkeypatch.setattr(mod, "_send", AsyncMock(return_value="layer0: hash=123 time=0.50"))
    monkeypatch.setattr(mod, "_args", _ARGS)
    result = await mod.debug_animator("/Player")
    mod._send.assert_called_once_with("debug_animator", {"path": "/Player"})
    assert isinstance(result, str)


@pytest.mark.asyncio
async def test_debug_physics_default_radius(monkeypatch):
    import unity_mcp.tools.generated.catalog_tools as mod
    monkeypatch.setattr(mod, "_send", AsyncMock(return_value="rb: vel=(0,0,0)"))
    monkeypatch.setattr(mod, "_args", _ARGS)
    await mod.debug_physics("/Enemy")
    call_args = mod._send.call_args[0]
    assert call_args[0] == "debug_physics"
    assert call_args[1]["path"] == "/Enemy"
    assert call_args[1]["radius"] == 5.0


@pytest.mark.asyncio
async def test_debug_physics_custom_radius(monkeypatch):
    import unity_mcp.tools.generated.catalog_tools as mod
    monkeypatch.setattr(mod, "_send", AsyncMock(return_value="nearby(10.0m): 3 colliders"))
    monkeypatch.setattr(mod, "_args", _ARGS)
    await mod.debug_physics("/Boss", radius=10.0)
    sent = mod._send.call_args[0][1]
    assert sent["radius"] == 10.0


