"""TDD tests for ask_user — interactive question card via Unity UI (FORWARD: SV4)."""
import pytest
from unittest.mock import AsyncMock
from mcp.server.mcpserver.exceptions import ToolError


@pytest.fixture
def mock_send():
    return AsyncMock(return_value='{"Color?":"Red"}')


@pytest.fixture(autouse=True)
def patch_ask_user(mock_send, monkeypatch):
    import unity_mcp.tools.generated.catalog_tools as mod  # ask_user is generated by the tool catalog (SV4)
    monkeypatch.setattr(mod, "_send", mock_send)
    monkeypatch.setattr(mod, "_args", lambda **kw: {k: v for k, v in kw.items() if v is not None})


async def test_ask_user_sends_cmd_and_args(mock_send):
    from unity_mcp.tools.ask_user_tool import ask_user
    questions = '[{"question":"Color?","options":[{"label":"Red"}]}]'
    result = await ask_user(questions)
    mock_send.assert_called_once_with("ask_user", {"questions": questions})
    assert result == '{"Color?":"Red"}'


async def test_ask_user_returns_result_unchanged(mock_send):
    from unity_mcp.tools.ask_user_tool import ask_user
    mock_send.return_value = '{"Confirm?":"Yes"}'
    result = await ask_user("[]")
    assert result == '{"Confirm?":"Yes"}'


async def test_ask_user_propagates_exception(mock_send):
    from unity_mcp.tools.ask_user_tool import ask_user
    mock_send.side_effect = ToolError("timeout")
    with pytest.raises(ToolError):
        await ask_user("[]")
